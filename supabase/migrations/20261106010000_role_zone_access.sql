create or replace function public.current_user_can_access_zone(p_zone text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.status = 'active'
      and (
        p.role in ('admin', 'aereo')
        or p_zone = any(p.allowed_zones)
      )
  );
$$;

create or replace function public.record_lot_codes(p_payload jsonb)
returns table (lot_code text)
language sql
immutable
parallel safe
set search_path = ''
as $$
  with recursive json_walk(value) as (
    select coalesce(p_payload, 'null'::jsonb)
    union all
    select child.value
    from json_walk node
    cross join lateral (
      select object_entry.value
      from jsonb_each(
        case when jsonb_typeof(node.value) = 'object' then node.value else '{}'::jsonb end
      ) object_entry
      union all
      select array_item.value
      from jsonb_array_elements(
        case when jsonb_typeof(node.value) = 'array' then node.value else '[]'::jsonb end
      ) array_item
    ) child
  )
  select nullif(trim(entry.value #>> '{}'), '')
  from json_walk node
  cross join lateral jsonb_each(
    case when jsonb_typeof(node.value) = 'object' then node.value else '{}'::jsonb end
  ) entry
  where lower(entry.key) ~ '^(id[_[:space:]]*)?lote([[:space:]]+[0-9]+)?$'
    and jsonb_typeof(entry.value) in ('string', 'number')
    and nullif(trim(entry.value #>> '{}'), '') is not null;
$$;

create or replace function public.record_zone_codes(p_payload jsonb)
returns table (zone text)
language sql
immutable
parallel safe
set search_path = ''
as $$
  with recursive json_walk(value) as (
    select coalesce(p_payload, 'null'::jsonb)
    union all
    select child.value
    from json_walk node
    cross join lateral (
      select object_entry.value
      from jsonb_each(
        case when jsonb_typeof(node.value) = 'object' then node.value else '{}'::jsonb end
      ) object_entry
      union all
      select array_item.value
      from jsonb_array_elements(
        case when jsonb_typeof(node.value) = 'array' then node.value else '[]'::jsonb end
      ) array_item
    ) child
  )
  select nullif(trim(entry.value #>> '{}'), '')
  from json_walk node
  cross join lateral jsonb_each(
    case when jsonb_typeof(node.value) = 'object' then node.value else '{}'::jsonb end
  ) entry
  where lower(entry.key) in ('zona', 'zone')
    and jsonb_typeof(entry.value) in ('string', 'number')
    and nullif(trim(entry.value #>> '{}'), '') is not null;
$$;

create or replace function public.current_user_can_access_record_scope(p_payload jsonb)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    not exists (
      select 1
      from public.record_lot_codes(p_payload) submitted_lot
      where not exists (
        select 1
        from public.field_lots lot
        where lot.lot_code = submitted_lot.lot_code
          and public.current_user_can_access_zone(lot.zone)
      )
    )
    and not exists (
      select 1
      from public.record_zone_codes(p_payload) submitted_zone
      where not public.current_user_can_access_zone(submitted_zone.zone)
    )
  ;
$$;

create or replace function public.set_member_access(
  p_user_id uuid,
  p_role text,
  p_allowed_zones text[] default '{}'
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_role text;
  caller_status text;
  active_admin_count integer;
  requested_zones text[] := coalesce(p_allowed_zones, '{}');
begin
  select role, status into caller_role, caller_status
  from public.profiles where id = (select auth.uid());
  if caller_role is distinct from 'admin' or caller_status is distinct from 'active' then
    raise exception 'Only an active administrator can change member access';
  end if;
  if p_role not in ('pending', 'aereo', 'terrestre', 'supervisor', 'admin') then
    raise exception 'Invalid member role';
  end if;
  if exists (
    select 1
    from unnest(requested_zones) as requested_zone(zone_name)
    where not exists (
      select 1 from public.field_zones zone where zone.zone = requested_zone.zone_name
    )
  ) then
    raise exception 'One or more zones are invalid';
  end if;

  if p_user_id = (select auth.uid()) and p_role <> 'admin' then
    raise exception 'An administrator cannot remove their own administrator role';
  end if;
  if p_role <> 'admin' then
    select count(*) into active_admin_count
    from public.profiles where role = 'admin' and status = 'active';
    if active_admin_count <= 1 and exists (
      select 1 from public.profiles where id = p_user_id and role = 'admin' and status = 'active'
    ) then
      raise exception 'At least one active administrator must remain';
    end if;
  end if;

  update public.profiles
  set role = p_role,
      status = case when p_role = 'pending' then 'pending' else 'active' end,
      allowed_zones = case
        when p_role in ('admin', 'aereo') then coalesce(
          (select array_agg(zone order by zone) from public.field_zones),
          '{}'
        )
        else array(select distinct unnest(requested_zones) order by 1)
      end
  where id = p_user_id;
  if not found then
    raise exception 'Member not found';
  end if;
end;
$$;

create or replace function public.set_member_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.set_member_access(p_user_id, p_role, '{}');
end;
$$;

create or replace function public.review_field_record(p_record_id uuid, p_decision text, p_note text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_role text;
  caller_status text;
begin
  select role, status into caller_role, caller_status
  from public.profiles where id = (select auth.uid());
  if caller_status is distinct from 'active' or caller_role not in ('admin', 'supervisor') then
    raise exception 'Only an active supervisor or administrator can review records';
  end if;
  if p_decision not in ('approved', 'rejected') then
    raise exception 'Invalid review decision';
  end if;
  if p_note is not null and length(p_note) > 2000 then
    raise exception 'Review note is too long';
  end if;

  update public.field_records
  set review_status = p_decision,
      reviewed_by = (select auth.uid()),
      reviewed_at = now(),
      review_note = nullif(trim(p_note), '')
  where id = p_record_id
    and review_status = 'pending'
    and owner_id <> (select auth.uid())
    and public.current_user_can_access_record_scope(datos);
  if not found then
    raise exception 'Record not found, already reviewed, outside your assigned zones, or owned by the reviewer';
  end if;
end;
$$;

